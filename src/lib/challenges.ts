export interface OrderChallenge {
  id: string;
  kind: "order";
  domain: string; // نطاق تربوي: خطط وتقويم، نظريات، ميدان...
  title: string; // ما يُطلب ترتيبه
  items: string[]; // بالترتيب الصحيح
  explain: string; // تفسير التسلسل
}

export interface FillChallenge {
  id: string;
  kind: "fill";
  domain: string;
  before: string; // الجزء قبل الفراغ
  right: string; // الكلمة الصحيحة
  after: string; // الجزء بعد الفراغ
  decoys: string[]; // ثلاث كلمات مشتتة
  explain: string;
}

export interface ProduceChallenge {
  id: string;
  kind: "produce";
  domain: string;
  prompt: string; // ما يُطلب كتابته
  requires: string[][]; // لكل مجموعة عناصر بديلة مقبولة — يجب تحقق كل المجموعات
  tips: string[]; // تلميحات قبل الكتابة
  minWords: number; // حد أدنى للكلمات
  model: string; // نموذج إجابة
}

export type Challenge = OrderChallenge | FillChallenge | ProduceChallenge;

// ---------- تطبيع عربي للتحقق التضميني ----------
// يوحد الهمزات والتاء المربوطة والألف المقصورة ويحذف التشكيل والتطويل.

export function normalizeAr(s: string): string {
  return s
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "") // تشكيل وتطويل
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[^\u0621-\u064A\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const wordCount = (s: string) => normalizeAr(s).split(" ").filter(Boolean).length;

/** تحقق الإنتاج: كل مجموعة من requires تُحقَّق بوجود أحد كلماتها بعد التطبيع */
export function produceCheck(text: string, requires: string[][]) {
  const t = normalizeAr(text);
  return requires.map((group) => ({
    anyOf: group,
    ok: group.some((k) => t.includes(normalizeAr(k))),
  }));
}

export const produceSatisfied = (text: string, c: ProduceChallenge, words: number) =>
  words >= c.minWords && produceCheck(text, c.requires).every((g) => g.ok);

