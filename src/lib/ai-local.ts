/** أفضل مفهوم في المكتبة يطابق السؤال، وإن وجد */
function findBestConcept(q: string): { concept: (typeof CONCEPTS)[number]; score: number } | null {
  const tokens = normalize(q).split(" ").filter((w) => w.length >= 3 && !STOPWORDS.has(w));
  if (!tokens.length) return null;
  let best: { concept: (typeof CONCEPTS)[number]; score: number } | null = null;
  const scored: { c: (typeof CONCEPTS)[number]; s: number }[] = [];
  for (const c of CONCEPTS) {
    const title = normalize(c.title);
    const chapter = normalize(c.chapter);
    const expl = normalize(c.explanation);
    const ex = normalize(c.example + " " + (c.examples ?? []).join(" "));
    let s = 0;
    for (const t of tokens) {
      if (title.includes(t)) s += 4;
      else if (chapter.includes(t)) s += 2;
      else if (expl.includes(t)) s += 1;
      else if (ex.includes(t)) s += 1;
    }
    if (s > 0) scored.push({ c, s });
    if (!best || s > best.score) best = { concept: c, score: s };
  }
  return best && best.score >= 6 ? best : null;
}

/** جواب المساعد المحلي — فوري، بلا شبكة، بلا مفاتيح */
export async function answerLocally(question: string, _history?: LocalChatMessage[]): Promise<string> {
  // مهلة قصيرة تعطي إحساس التفكير الطبيعي دون تأخير مزعج
  await new Promise((r) => setTimeout(r, 350 + Math.random() * 450));
  try {
    const q = normalize(question);

    // ١) الإجابات الخبيرة الجاهزة — الأدق أولاً
    for (const intent of INTENTS) {
      if (intent.keys.some((k) => q.includes(k))) return intent.answer;
    }

    // ٢) البحث في مكتبة المفاهيم
    const hit = findBestConcept(question);
    if (hit) {
      const c = hit.concept;
      const courseName = COURSES.find((x) => x.id === c.courseId)?.name ?? "";
      const near = CONCEPTS.filter((x) => x.id !== c.id && normalize(x.chapter) === normalize(c.chapter))
        .slice(0, 2)
        .map((x) => `«${x.title}»`);
      const parts = [
        `من مكتبتك التربوية — «${c.title}»${courseName ? ` (${courseName})` : ""}:`,
        c.explanation,
        c.example ? `مثال صفّي: ${c.example}` : "",
      ].filter(Boolean);
      if (near.length) parts.push(`مواضيع قريبة تستحق الاطلاع: ${near.join(" و")}.`);
      return parts.join("\n\n");
    }

    // ٣) رد التوجيه المهذب
    return [
      "سؤالك خارج مكتبتي الجاهزة في هذه الصيغة — جرّب صياغته بكلمات تربوية أوضح، وسأبحث لك في المكتبة فورًا.",
      "مثال: «ما الفرق بين التقويم التكويني والختامي؟»، أو «كيف أتعامل مع صف صاخب؟»، أو «اشرح لي التعلم التكيفي».",
      "ويمكنك دائماً استعراض المفاهيم مباشرة من تبويب المكتبة — وتدريبها من تبويب الاختبارات.",
    ].join("\n\n");
  } catch {
    return "حدث خلل مؤقت في المحرك المحلي — أعد طرح سؤالك من فضلك.";
  }
}
