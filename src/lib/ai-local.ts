/** تطبيع عربي للبحث: نزع التشكيل والتطويل وتوحيد الهمزات والتاء المربوطة */
function normalize(t: string): string {
  return t
    .replace(/[\u064B-\u0652\u0670\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/\s+/g, " ")
    .trim();
}

