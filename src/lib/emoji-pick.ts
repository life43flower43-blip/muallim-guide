function hash(s: string) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

/** يعيد رمزًا لكل عنوان، دون تكرار داخل القائمة نفسها */
export function pickEmojis(titles: string[]): string[] {
  const used = new Set<string>();
  return titles.map((t) => {
    for (const [re, opts] of KEYWORDS) {
      if (!re.test(t)) continue;
      const e = opts.find((o) => !used.has(o));
      if (e) { used.add(e); return e; }
    }
    let k = hash(t) % POOL.length;
    for (let n = 0; n < POOL.length && used.has(POOL[k]); n++) k = (k + 1) % POOL.length;
    used.add(POOL[k]);
    return POOL[k];
  });
}
