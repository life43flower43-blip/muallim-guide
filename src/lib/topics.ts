export const topicBySlug = (slug: string) => TOPICS.find((t) => t.slug === slug);

const hit = (text: string, kw: string[]) => kw.some((w) => text.includes(w));

/** مقالات الموضوع: ما طابق وسومه أو عنوانه */
export function topicArticles(t: Topic): Article[] {
  return allArticles().filter((a) => a.tags.some((tag) => hit(tag, t.kw)) || hit(a.title, t.kw));
}

/** مفاهيم الموضوع: ما طابق عنوانه */
export function topicConcepts(t: Topic, limit = 30): Concept[] {
  return publicBank().concepts.filter((c) => hit(c.title, t.kw)).slice(0, limit);
}

/** صفحة الموضوع الأقرب إلى وسم مقال، إن وُجدت */
export function topicForTag(tag: string): Topic | undefined {
  return TOPICS.find((t) => t.kw.some((w) => tag.includes(w) || w.includes(tag)) || t.name === tag);
}
