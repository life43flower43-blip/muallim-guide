export const FIRST_DAY_ALL_IDS: string[] = FIRST_DAY_SECTIONS.flatMap((s) =>
  s.items.map((i) => i.id)
);

/** نص جاهز للمشاركة — يلخص ما أنجزته وما بقي، بلا أرقام ولا لاتيني */
export function composeFirstDayText(checked: string[]): string {
  const lines: string[] = ["قائمة يومي الأول في المدرسة — من تطبيق تربوي:"];
  for (const s of FIRST_DAY_SECTIONS) {
    lines.push("");
    lines.push(`«${s.title}»`);
    for (const i of s.items) {
      lines.push(`${checked.includes(i.id) ? "أنجزته" : "بانتظاري"}: ${i.text}`);
    }
  }
  const done = s1(checked);
  lines.push("");
  lines.push(`جاهزيتي: ${done}`);
  return lines.join("\n");
}

function s1(checked: string[]): string {
  const n = checked.length;
  if (n === 0) return "أستعد الآن من الصفر";
  if (n < 5) return "خطواتي الأولى نحو الميدان";
  if (n < FIRST_DAY_ALL_IDS.length) return "قاربت الجاهزية الكاملة";
  return "جاهز لليوم الأول تمامًا";
}

/** كلمة جاهزية معروضة في أعلى القائمة */
export function firstDayReadinessWord(checked: string[]): string {
  return s1(checked);
}
