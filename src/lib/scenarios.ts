export const scenarioById = (id: string) => SCENARIOS.find((s) => s.id === id);

export const SCENARIO_CATEGORIES: string[] = Array.from(
  new Set(SCENARIOS.map((s) => s.category))
);

export const bestIndexOf = (s: Scenario) => s.options.findIndex((o) => o.score === "best");

export const scoreColor = (score: ScenarioScore) =>
  score === "best" ? "#6D28D9" : score === "ok" ? "#F59E0B" : "#DC2626";

export const scoreLabel = (score: ScenarioScore) =>
  score === "best" ? "قرار ممتاز" : score === "ok" ? "قرار مقبول" : "قرار فيه مخاطرة";

// بناء جولة: غير المحلول أولاً ثم عشوائي، بحد أقصى n
export const buildScenarioRun = (solvedIds: string[], n = 10): Scenario[] => {
  const solved = new Set(solvedIds);
  const fresh = SCENARIOS.filter((s) => !solved.has(s.id));
  const done = SCENARIOS.filter((s) => solved.has(s.id));
  return [...fresh, ...done].slice(0, Math.min(n, SCENARIOS.length));
};

