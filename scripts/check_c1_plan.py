def main():
    with open("/home/z/my-project/public/data/qbank.json", encoding="utf-8") as f:
        bank = json.load(f)
    titles = {c["title"] for c in bank["concepts"]}
    stems = [q["question"] for q in bank["questions"]]

    all_titles = []
    for ch, ts in PLAN:
        all_titles += ts
    dupes_inside = len(all_titles) - len(set(all_titles))
    print("عدد الفصول:", len(PLAN), "| عدد المفاهيم المخططة:", len(all_titles))
    print("تكرارات داخلية:", dupes_inside)

    errors = []
    for ch, ts in PLAN:
        if ch in titles:
            errors.append(f"فصل باسم موجود في البنك: {ch}")
        for t in ts:
            if t in titles:
                errors.append(f"عنوان مكرر مع البنك: {t}")
    # كلمات مميزة لكل عنوان تُفحص ضد نصوص الأسئلة (لتقليل التداخل الموضوعي الحاد)
    key_words = [
        "التناظر اللفظي", "الاستنتاج المنطقي اللفظي", "المتتاليات العددية",
        "النسبة والتناسب", "الحيل الحسابية", "الأنماط الرمزية",
        "الترتيب والمقارنة", "التصنيف والاستبعاد", "الاستدلال القضوي",
        "الاتجاهات والمسافات", "التمثيل الفراغي", "قراءة الجداول",
        "الترتيب الزمني", "الاستقراء وإيجاد القاعدة",
    ]
    for t in all_titles:
        for kw in key_words:
            if t == kw:
                errors.append(f"عنوان يحاكي مفهومًا قائمًا: {t}")
    if errors:
        print("!!! أخطاء:", len(errors))
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    print("✔ لا تصادمات — الخطة آمنة (١٣ فصلًا × ١٠ مفاهيم = ١٣٠ مفهومًا)")


if __name__ == "__main__":
    main()
