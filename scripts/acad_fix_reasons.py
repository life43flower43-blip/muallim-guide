# -*- coding: utf-8 -*-
"""كسر القوالب الآلية في أسباب الإجابات: «المشتتات» → صياغات أكاديمية متنوعة، وتنويع بدايات «الصحيح لأن»."""
import json, re
from collections import Counter

PATH = '/home/z/my-project/src/data/qbank.json'
d = json.load(open(PATH, encoding='utf-8'))

# مجمعات صياغة أكاديمية سليمة نحوًا — تُدار بدوران محكوم بهوية السؤال لضمان التنوع
POOL_ALT = [
    'أما الخيارات الأخرى فلا تصح لأنها ',
    'ولا يصح أيٌّ من الخيارات الباقية لأنها ',
    'وتسقط الخيارات الأخرى لأنها ',
    'أما البدائل الأخرى فتنحرف عن مضمون السؤال لأنها ',
    'وتبقى الخيارات الأخرى مرفوضة لأنها ',
]
POOL_ALT_LAN = [
    'أما الخيارات الأخرى فلا تصح لأن ',
    'ولا يصح أيٌّ من البدائل لأن ',
    'وتسقط الخيارات الأخرى لأن ',
    'أما البدائل الأخرى فتنحرف عن مضمون السؤال لأن ',
]
POOL_CORRECT = [
    'وجه الصواب أن ',
    'الإجابة الصحيحة لأن ',
    'يكمن الصواب في أن ',
    'ووجهة هذا الخيار الصحيح أن ',
]
# استبدالات محددة (أولًا الأطول كي لا يفسد الأقصر الأطول)
ORDINALS = [
    ('المشتتة الأولى خاطئة', 'الخيار الأول لا يصح'),
    ('المشتتة الثانية خاطئة', 'الخيار الثاني لا يصح'),
    ('المشتتة الثالثة خاطئة', 'الخيار الثالث لا يصح'),
    ('المشتتة الرابعة خاطئة', 'الخيار الرابع لا يصح'),
    ('المشتتات الأولى والثانية', 'الخيارات الأولى والثانية'),
    ('المشتتات الأولى والثالثة', 'الخيارات الأولى والثالثة'),
    ('المشتتات الأولى والرابعة', 'الخيارات الأولى والرابعة'),
    ('المشتتات الثانية والثالثة', 'الخيارات الثانية والثالثة'),
    ('المشتتات الأخرى خاطئة', 'الخيارات الأخرى لا تصح'),
    ('أما المشتتات فهي خاطئة', 'أما الخيارات الأخرى فلا تصح'),
    ('المشتتات خاطئة', 'الخيارات الأخرى لا تصح'),
]
stats = Counter()

def rid(q):
    m = re.search(r'\d+', str(q.get('id', '')))
    return int(m.group()) if m else 0

for q in d['questions']:
    r = str(q['reason'])
    if 'المشتت' not in r and 'الخيارات الأخرى خاطئة' not in r and not r.startswith('الصحيح لأن '):
        continue
    k = rid(q)
    # ١) بدل «المشتتات/المشتتة» بأسماء الخيارات مع تسلسل زمني محكم
    for old, new in ORDINALS:
        r = r.replace(old, new)
    r = r.replace('المشتتات خاطئة لأنها ', POOL_ALT[k % len(POOL_ALT)])
    r = r.replace('المشتتات خاطئة لأن ', POOL_ALT_LAN[k % len(POOL_ALT_LAN)])
    r = r.replace('المشتتات خاطئة، لأنها ', POOL_ALT[k % len(POOL_ALT)])
    r = r.replace('المشتتات لا تصح لأنها ', POOL_ALT[(k + 1) % len(POOL_ALT)])
    # ٢) «الخيارات الأخرى خاطئة لأنها» قالب متكرر
    r = r.replace('الخيارات الأخرى خاطئة لأنها ', POOL_ALT[(k + 2) % len(POOL_ALT)])
    r = r.replace('الخيارات الأخرى خاطئة لأن ', POOL_ALT_LAN[(k + 1) % len(POOL_ALT_LAN)])
    # ٣) بقايا عامة
    r = r.replace('المشتتات', 'الخيارات البديلة')
    r = r.replace('المشتتة', 'الخيار البديل')
    r = re.sub(r'\bالمشتت\b(?!ات)', 'الخيار البديل', r)
    # ٤) بداية «الصحيح لأن» المتكررة
    if r.startswith('الصحيح لأن '):
        r = POOL_CORRECT[k % len(POOL_CORRECT)] + r[len('الصحيح لأن '):]
    # ٥) توحيد: «الخيار البديل» لوحده أسلوب ركيك في بعض السياقات — أدق صياغة
    q['reason'] = r
    stats['عولج'] += 1

# عدّ المتبقي
left = sum(1 for q in d['questions'] if 'المشتت' in str(q['reason']))
stats['متبقي بالمشتت'] = left

json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(dict(stats))

