#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
توحيد موقف أنماط التعلم (مرحلة 4) — وفق جولتي المراجع 9 و12:
الادعاء المدعوم: الطلاب لديهم تفضيلات، وتنويع التمثيل قد يساعد.
الادعاء غير المدعوم: مطابقة التدريس لنمط ثابت ترفع التحصيل.
Q13727 يبقى شاهده (لا تعديل)، وQ9596/Q12965/Q12966/Q714/Q694 تُرقَّى.
"""
import json

BANK = 'public/data/qbank.json'
d = json.load(open(BANK, encoding='utf-8'))
Q = {q['id']: q for q in d['questions']}
log = []

def set_reason(qid, new):
    Q[qid]['reason'] = new
    log.append(f'{qid}[reason]: إعادة صياغة')

def set_option(qid, idx, new_text):
    o = Q[qid]['options'][idx - 1]
    old = o['text']
    o['text'] = new_text
    if Q[qid].get('correct') == old:
        Q[qid]['correct'] = new_text
    log.append(f'{qid}[خ{idx}]: {old[:45]}… → {new_text[:45]}…')

def set_question(qid, old_frag, new_frag):
    t = Q[qid]['question']
    assert old_frag in t, f'{qid}: لا يوجد: {old_frag[:40]}'
    Q[qid]['question'] = t.replace(old_frag, new_frag, 1)
    log.append(f'{qid}[question]: {old_frag[:40]}… → {new_frag[:40]}…')

# ═══ Q9596: حذف الادعاء غير المدعوم «ينجح أكثر حين يناسبه نمطه» ═══
set_reason('Q9596',
    'نمط التعلم ميل مفضل لا قدرة حصرية؛ فالطالب قد يرتاح بداية إلى طريقة دون أخرى، لكن اختيار طريقة التدريس يعتمد على هدف التعلم وطبيعة المادة واحتياجاته الفعلية لا على مطابقة تفضيله المعلن، وتوسيع أنماطه مرونة تستحق التدريب؛ فالعبارة صحيحة.')

# ═══ Q12965: من تصنيف الطلاب إلى تنويع وسائل العرض ═══
set_question('Q12965',
    'ما القنوات الثلاث النموذجية في التفاضل بحسب أنماط التعلم؟',
    'ما القنوات الثلاث الشائعة لتنويع وسائل عرض المحتوى داخل الحصة؟')
set_reason('Q12965',
    'تنويع وسائل العرض يقوم عادة على ثلاث قنوات: بصرية بالصور والمخططات، وسمعية بالشرح والمناقشة، وحركية بالتجريب والبناء، ولكل قناة أدواتها داخل الحصة. وهذا تنويع في تمثيل المحتوى ينتفع به الجميع بحسب طبيعة المادة، ولا يعني تصنيف الطلاب إلى فئات ثابتة يقرر كل منها طريقة تدريسها. فالتقسيمات الأخرى ذكائية أو زمنية أو ثقافية لا تمثل قنوات العرض.')

# ═══ Q12966: من ضمان أثر للجميع إلى ملاءمة التمثيل للمحتوى ═══
set_question('Q12966',
    'أي خلاصة تعكس البصيرة الأدق حول أثر تنويع قنوات العرض داخل الحصة؟',
    'أي خلاصة تعكس الموقف الأدق حول تنويع قنوات العرض داخل الحصة؟')
set_option('Q12966', 2,
    'التنويع بين الكلمات والصور والتطبيق قد يساعد على ترسيخ المحتوى حين يناسب طبيعته وهدف الدرس')
set_reason('Q12966',
    'الخلاصة الأدق أن تعدد قنوات التمثيل يتيح ترميزاً متعدد المداخل وقد يدعم الفهم والاحتفاظ حين يتناسب مع المحتوى وهدف الدرس، دون ضمان أثر واحد مضمون لكل متعلم. والحصر في قناة واحدة يضيّق فرص التمثيل، والاكتفاء بالشرح لبعض الطلاب يهدر هذه الفرص، ولا توجد قناة واحدة ينتفع بها طالب دون غيره بحسب نمط ثابت.')

# ═══ Q714: من «الطريقة المثلى» إلى تجربة مدروسة بمتابعة ═══
set_option('Q714', 2,
    'تجربة أسلوب التكرار الصوتي مع متابعة أثره في أدائها ومقارنته بطرق أخرى مناسبة للمحتوى')
set_reason('Q714',
    'الخيار الصحيح يوازن بين الملاحظة والمنهج: ملاحظة أولية تشير إلى فائدة من السمع والتكرار مع ليلى، فالإجراء السليم تجربة هذا الأسلوب ومتابعة أثره الفعلي في أدائها ومقارنته بطرق أخرى بحسب طبيعة المحتوى، لا تصنيف الطالبة بنمط ثابت يقرر «الطريقة المثلى» لكل موقف. أما بقية الخيارات فعزل للطالبة أو ظلم لها أو تقليص لفرصها بلا سند.')

# ═══ Q694: تبرير التنويع دون افتراض أنماط ثابتة ═══
set_reason('Q694',
    'الجواب الصحيح هو تنويع أنشطة الدروس لأنه يتيح استيعاب الفروق الفردية في الاستعدادات والاحتياجات الناتجة عن التفاعل بين الوراثة والبيئة، ويمنح المتعلمين مداخل متعددة للمهمة بحسب طبيعتها، دون افتراض أن الطلاب ينقسمون إلى أنماط ثابتة تُطابَق طرق تدريسها. الخيار الأول خاطئ لأنه يهمل الفروق، والثاني يحرم المتقدمين من التحدي، والرابع يقلص فرص التعلم.')

json.dump(d, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False)
with open('review/r5_learning_styles_log.md', 'w', encoding='utf-8') as f:
    f.write('# سجل توحيد أنماط التعلم (مرحلة 4)\n\n')
    for line in log:
        f.write(f'- {line}\n')
print(f'أُنجز {len(log)} تعديلًا. Q13727 بقي كما هو (متسق أصلًا).')
