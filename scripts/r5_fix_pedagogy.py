import json

BANK = 'public/data/qbank.json'
d = json.load(open(BANK, encoding='utf-8'))
Q = {q['id']: q for q in d['questions']}
log = []

def set_reason(qid, new):
    Q[qid]['reason'] = new
    log.append(f'{qid}[reason]: إعادة صياغة كاملة')

def set_question(qid, new):
    Q[qid]['question'] = new
    log.append(f'{qid}[question]: إعادة صياغة')

def set_option(qid, idx, new_text):
    o = Q[qid]['options'][idx - 1]
    old = o['text']
    o['text'] = new_text
    if Q[qid].get('correct') == old:
        Q[qid]['correct'] = new_text
    log.append(f'{qid}[خ{idx}]: {old[:45]}… → {new_text[:45]}…')

def replace(qid, field, old, new):
    t = Q[qid][field]
    assert old in t, f'{qid}[{field}]: لا يوجد: {old[:40]}'
    Q[qid][field] = t.replace(old, new, 1)
    log.append(f'{qid}[{field}]: {old[:45]}… → {new[:45]}…')

