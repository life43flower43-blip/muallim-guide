# -*- coding: utf-8 -*-
"""الجولة الثانية: تنظيف بقايا القوالب — المشتت الترتيبي، «الخيار البديل الأول»، «الصحيح صحيح»."""
import json, re
from collections import Counter

PATH = '/home/z/my-project/src/data/qbank.json'
d = json.load(open(PATH, encoding='utf-8'))
stats = Counter()

ORD = [
    ('المشتتتان الثالثة والرابعة', 'الخياران الثالث والرابع'),
    ('المشتتان الثالثة والرابعة', 'الخياران الثالث والرابع'),
    ('المشتتان الأول والثاني', 'الخياران الأول والثاني'),
    ('المشتت الأول', 'الخيار الأول'),
    ('المشتت الثاني', 'الخيار الثاني'),
    ('المشتت الثالث', 'الخيار الثالث'),
    ('المشتت الرابع', 'الخيار الرابع'),
    ('الخيار البديل الأول', 'الخيار الأول'),
    ('الخيار البديل الثاني', 'الخيار الثاني'),
    ('الخيار البديل الثالث', 'الخيار الثالث'),
    ('الخيار البديل الرابع', 'الخيار الرابع'),
    ('الخيار البديل الوحيد', 'الخيار الوحيد'),
    ('الخيارات البديلة الأولى والثانية', 'الخيارات الأولى والثانية'),
    ('الخيارات البديلة الثالثة والرابعة', 'الخيارات الثالثة والرابعة'),
    ('الخيار البديل الصحيح', 'الخيار الصحيح'),
]
CORRECT_POOL = [
    'صواب هذا الخيار لأن ',
    'وجه الصواب أن ',
    'الإجابة الصحيحة لأن ',
    'يكمن الصواب في أن ',
]

for q in d['questions']:
    r = str(q['reason'])
    orig = r
    for old, new in ORD:
        r = r.replace(old, new)
    # «الصحيح صحيح لأن» → تنويع محكوم بالهوية
    if r.startswith('الصحيح صحيح لأن '):
        k = int(re.search(r'\d+', str(q.get('id', '0'))).group()) if re.search(r'\d+', str(q.get('id', '0'))) else 0
        r = CORRECT_POOL[k % len(CORRECT_POOL)] + r[len('الصحيح صحيح لأن '):]
        stats['صحيح صحيح'] += 1
    # «الخيار البديل» المتبقي بلا ترتيب → «الخيار البديل» يظل مقبولًا، لكن «الخيار البديلُ» إعرابًا لا يلزم
    if r != orig:
        q['reason'] = r
        stats['عدل'] += 1

left = sum(1 for q in d['questions'] if 'المشتت' in str(q['reason']) and q['id'] != 'Q186')
left2 = sum(1 for q in d['questions'] if 'الصحيح صحيح' in str(q['reason']))
print(dict(stats), '| متبقٍ بالمشتت (غير Q186):', left, '| متبقٍ صحيح صحيح:', left2)

json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
