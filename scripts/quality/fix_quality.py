counts = Counter()
def fix_text(t):
    def sub(m):
        tok = m.group(0)
        if tok in MAP:
            counts[tok] += 1
            return MAP[tok]
        return tok
    return TOKEN.sub(sub, t)

def apply_q(q):
    q["question"] = fix_text(q.get("question", ""))
    q["reason"] = fix_text(q.get("reason", ""))
    for o in q.get("options", []):
        if isinstance(o, dict):
            o["text"] = fix_text(o.get("text", ""))

def apply_c(c):
    c["title"] = fix_text(c.get("title", ""))
    c["explanation"] = fix_text(c.get("explanation", ""))
    ex = c.get("examples")
    if isinstance(ex, list):
        c["examples"] = [fix_text(str(x)) for x in ex]
    elif ex:
        c["examples"] = fix_text(str(ex))
    if c.get("example"):
        c["example"] = fix_text(str(c["example"]))

for q in questions:
    apply_q(q)
for c in concepts:
    apply_c(c)
