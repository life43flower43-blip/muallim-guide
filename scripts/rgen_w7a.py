def _run_self_check():
    """فحص ذاتي شامل: العدادات، الأنواع، الإجابات، التفرد، الأطوال الدنيا، أسماء الفصلين."""
    import re
    from collections import Counter

    errors = []
    ch_self = "ل. التعليم الذاتي"
    ch_elearn = "م. التعليم الإلكتروني والتعليم عن بُعد"

    # 1) عدد المفاهيم = 23 وcourse = G1
    if len(NEW_CONCEPTS) != 23:
        errors.append("عدد المفاهيم = " + str(len(NEW_CONCEPTS)) + " والمتوقع 23")
    for c in NEW_CONCEPTS:
        if c["course"] != "G1":
            errors.append(c["cid"] + ": course لا يساوي G1")

    # 2) أسماء الفصلين حرفية بالتوزيع 12 + 11
    n_self = sum(1 for c in NEW_CONCEPTS if c["chapter"] == ch_self)
    n_elearn = sum(1 for c in NEW_CONCEPTS if c["chapter"] == ch_elearn)
    if n_self != 12:
        errors.append("فصل «ل. التعليم الذاتي» يحوي " + str(n_self) + " مفهوماً والمتوقع 12")
    if n_elearn != 11:
        errors.append("فصل «م. التعليم الإلكتروني والتعليم عن بُعد» يحوي " + str(n_elearn) + " مفهوماً والمتوقع 11")
    for c in NEW_CONCEPTS:
        if c["chapter"] not in (ch_self, ch_elearn):
            errors.append(c["cid"] + ": اسم الفصل غير حرفي: " + c["chapter"])

    # 3) تفرّد المعرفات وأسماء المفاهيم والشروح والأمثلة
    cids = [c["cid"] for c in NEW_CONCEPTS]
    if len(set(cids)) != len(cids):
        errors.append("تكرار في معرفات المفاهيم")
    names = [c["name"] for c in NEW_CONCEPTS]
    if len(set(names)) != len(names):
        errors.append("تكرار في أسماء المفاهيم")
    if len(set(c["explanation"] for c in NEW_CONCEPTS)) != len(NEW_CONCEPTS):
        errors.append("تكرار في نصوص الشروح")
    if len(set(c["example"] for c in NEW_CONCEPTS)) != len(NEW_CONCEPTS):
        errors.append("تكرار في نصوص الأمثلة")

    # 4) أطوال دنيا للمفاهيم
    for c in NEW_CONCEPTS:
        if len(c["explanation"]) < 120:
            errors.append(c["cid"] + ": الشرح أقصر من 120 حرفاً")
        if len(c["example"]) < 100:
            errors.append(c["cid"] + ": المثال أقصر من 100 حرف")

    # 5) عدد الأسئلة = 46 وتفرّد نصوصها
    if len(QUESTIONS) != 46:
        errors.append("عدد الأسئلة = " + str(len(QUESTIONS)) + " والمتوقع 46")
    qtexts = [q["question"] for q in QUESTIONS]
    if len(set(qtexts)) != len(qtexts):
        errors.append("تكرار في نصوص الأسئلة")

    # 6) لكل مفهوم mcq واحد + tf واحد بالضبط
    per = Counter((q["cid"], q["qtype"]) for q in QUESTIONS)
    for cid in cids:
        if per.get((cid, "mcq"), 0) != 1:
            errors.append(cid + ": يلزم سؤال mcq واحد بالضبط (الموجود " + str(per.get((cid, "mcq"), 0)) + ")")
        if per.get((cid, "tf"), 0) != 1:
            errors.append(cid + ": يلزم سؤال tf واحد بالضبط (الموجود " + str(per.get((cid, "tf"), 0)) + ")")

    # 7) سلامة الخيارات والإجابات والأطوال وقالب الأسئلة
    for q in QUESTIONS:
        tag = q["cid"] + " (" + q["qtype"] + ")"
        if q["qtype"] == "mcq":
            opts = [q["a"], q["b"], q["c"], q["d"]]
            if len(set(opts)) != 4:
                errors.append(tag + ": الخيارات الأربعة ليست مختلفة تماماً")
            if q["correct"] not in opts:
                errors.append(tag + ": correct ليس نص أحد الخيارات حرفياً")
        elif q["qtype"] == "tf":
            if q["a"] != "صح" or q["b"] != "خطأ":
                errors.append(tag + ": يجب أن يكون a=صح وb=خطأ")
            if q["correct"] not in ("صح", "خطأ"):
                errors.append(tag + ": correct يجب أن يكون صح أو خطأ")
        else:
            errors.append(tag + ": qtype غير معروف")
        if len(q["reason"]) < 150:
            errors.append(tag + ": السبب أقصر من 150 حرفاً")
        if "من المفاهيم" in q["question"] and q["question"].strip().startswith("يُعد"):
            errors.append(tag + ": قالب ممنوع «يُعد ... من المفاهيم»")
        if q["diff"] not in ("سهل", "متوسط", "صعب"):
            errors.append(tag + ": قيمة الصعوبة غير معروفة")

    # 8) توزيع الصعوبة 12 / 25 / 9
    diff_counter = Counter(q["diff"] for q in QUESTIONS)
    if diff_counter.get("سهل", 0) != 12:
        errors.append("عدد أسئلة «سهل» = " + str(diff_counter.get("سهل", 0)) + " والمتوقع 12")
    if diff_counter.get("متوسط", 0) != 25:
        errors.append("عدد أسئلة «متوسط» = " + str(diff_counter.get("متوسط", 0)) + " والمتوقع 25")
    if diff_counter.get("صعب", 0) != 9:
        errors.append("عدد أسئلة «صعب» = " + str(diff_counter.get("صعب", 0)) + " والمتوقع 9")

    # 9) لا حروف لاتينية داخل النصوص العربية
    latin = re.compile(r"[A-Za-z]")
    for c in NEW_CONCEPTS:
        for key in ("name", "explanation", "example", "chapter"):
            if latin.search(c[key]):
                errors.append(c["cid"] + ": حروف لاتينية داخل الحقل " + key)
    for q in QUESTIONS:
        for key in ("question", "a", "b", "c", "d", "correct", "reason"):
            v = q.get(key)
            if isinstance(v, str) and latin.search(v):
                errors.append(q["cid"] + " (" + q["qtype"] + "): حروف لاتينية داخل الحقل " + key)

    if errors:
        raise AssertionError("SELF-CHECK FAILED:\n- " + "\n- ".join(errors))

    mcq_count = sum(1 for q in QUESTIONS if q["qtype"] == "mcq")
    tf_count = sum(1 for q in QUESTIONS if q["qtype"] == "tf")
    tf_counter = Counter(q["correct"] for q in QUESTIONS if q["qtype"] == "tf")

    print("عدد المفاهيم:", len(NEW_CONCEPTS),
          "| «" + ch_self + "» =", n_self,
          "| «" + ch_elearn + "» =", n_elearn)
    print("عدد الأسئلة:", len(QUESTIONS), "| mcq =", mcq_count, "| tf =", tf_count)
    print("توزيع الصعوبة: سهل =", diff_counter.get("سهل", 0),
          "| متوسط =", diff_counter.get("متوسط", 0),
          "| صعب =", diff_counter.get("صعب", 0))
    print("توزيع أسئلة الصواب والخطأ: صح =", tf_counter.get("صح", 0),
          "| خطأ =", tf_counter.get("خطأ", 0))
    print("SELF-CHECK OK")


if __name__ == "__main__":
    _run_self_check()
