# المفاهيم التي لها شرح متحرك (معرّف المفهوم: مفتاح الرسم)
ANIM = {
    "D1701": "normal", "D1708": "normal", "D1629": "targets", "D1692": "easiness", "C293": "easiness",
    "D1695": "discrim", "D1694": "discrim", "D1682": "specs", "D1683": "specs", "D1603": "formative", "C282": "formative",
    "D904": "directions", "D903": "directions", "D926": "erikson", "D974": "kohlberg", "D925": "zpd",
    "D1779": "lessonflow", "D1787": "waittime", "D1810": "jigsaw", "D1834": "differentiate",
}

def short(text, limit=330):
    """أول جمل الشرح حتى حد معقول، فلا تزدحم لوحة الشرح"""
    parts = re.split(r"(?<=[.؛])\s+", (text or "").replace("\n", " ").strip())
    out = ""
    for p in parts:
        if out and len(out) + len(p) > limit:
            break
        out = (out + " " + p).strip()
    return out

def main():
    d = json.load(open(BANK))
    qn = collections.Counter(q["conceptId"] for q in d["questions"])
    by_chapter = collections.defaultdict(list)
    for c in d["concepts"]:
        by_chapter[(c["courseId"], c["chapter"])].append(c)
    os.makedirs(OUT, exist_ok=True)
    for cid, (title, desc, ex, groups) in GROUPS.items():
        used = set()
        root = {"t": title, "d": desc, "c": ex, "k": []}
        for gt, gd, gc, chapters in groups:
            g = {"t": gt, "d": gd, "c": gc, "k": []}
            for ch in chapters:
                concepts = by_chapter.get((cid, ch))
                assert concepts, (cid, ch)
                used.add(ch)
                node = {"t": ch, "d": f"في هذا الفصل {len(concepts)} مفاهيم: " + "، ".join(c["title"] for c in concepts) + ".", "k": []}
                for c in concepts:
                    leaf = {"t": c["title"], "d": short(c["explanation"]), "c": c.get("example") or "", "cid": c["id"], "qn": qn[c["id"]]}
                    if c["id"] in ANIM:
                        leaf["a"] = ANIM[c["id"]]
                    node["k"].append(leaf)
                g["k"].append(node)
            root["k"].append(g)
        missing = {ch for (co, ch) in by_chapter if co == cid} - used
        assert not missing, (cid, missing)
        json.dump(root, open(f"{OUT}/{cid}.json", "w"), ensure_ascii=False, separators=(",", ":"))
        print(cid, sum(len(n["k"]) for g in root["k"] for n in g["k"]), "concepts")

if __name__ == "__main__":
    main()
