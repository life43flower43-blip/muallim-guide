for blk in report:
    head = re.match(r'^## (\d+)\.\s+(.+?)\s*(?:\((\d+)\))?\s*$', blk.splitlines()[0])
    if not head:
        continue
    no, title = int(head.group(1)), head.group(2).strip()
    items = []
    for ln in blk.splitlines()[1:]:
        t = ln.strip()
        mm = re.match(r'^\[(K|D)\]\s+(.*)$', t)
        if not mm:
            continue
        status, rest = mm.group(1), mm.group(2)
        src = tgt = None
        if ' ⟵ ' in rest:
            name_part, right = rest.split(' ⟵ ', 1)
            right = right.split(' + ')[0].split(' |')[0].strip()
            m2 = re.match(r'^(\S+)\s+\((.*)\)$', right)
            if m2:
                src, tgt = m2.group(1), m2.group(2).strip()
            name = name_part.strip()
        else:
            name = rest.split(' |')[0].strip()
        items.append([name, status, src, tgt])
    sections.append((no, title, items))

