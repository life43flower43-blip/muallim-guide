# SELF-CHECK: فحص ذاتي صارم للدفعة قبل التسليم
# ------------------------------------------------------------------
def _self_check() -> None:
    import re

    problems: list = []
    forbidden = re.compile(r"[A-Za-z0-9]")
    cjk = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3040-\u30ff\uac00-\ud7af]")
    huge = 10 ** 9

    def scan(text: str, where: str) -> None:
        hits = forbidden.findall(text)
        if hits:
            problems.append(f"محارف ممنوعة في {where}: {hits[:5]}")
        if cjk.search(text):
            problems.append(f"محارف شرق آسيوية في {where}")
        if "المشتتات" in text:
            problems.append(f"كلمة محظورة في {where}")

    # فحص القوائم والمعرفات
    if len(CONCEPTS) != 10:
        problems.append(f"عدد المفاهيم {len(CONCEPTS)} غير العشرة المطلوبة")
    if len(QUESTIONS) != 40:
        problems.append(f"عدد الأسئلة {len(QUESTIONS)} غير الأربعين المطلوبة")
    expected_cids = [f"D12{n}" for n in range(41, 51)]
    if [c["id"] for c in CONCEPTS] != expected_cids:
        problems.append("تسلسل معرفات المفاهيم غير مطابق للنطاق من ألف إلى عشرة")
    expected_qids = [f"Q{10000 + n}" for n in range(61, 101)]
    if [q["id"] for q in QUESTIONS] != expected_qids:
        problems.append("تسلسل معرفات الأسئلة غير مطابق للنطاق المطلوب")

    # فحص المفاهيم
    chapters_ok = ["ما وراء المعرفة والتعلم الذاتي"] * 5 + ["الدافعية والتعلم"] * 5
    seen_expl: set = set()
    seen_examples: set = set()
    seen_summary: set = set()
    seen_sentences: set = set()
    min_expl = (huge, "")
    min_example = (huge, "")
    for ci, c in enumerate(CONCEPTS):
        where = c["id"]
        if c.get("courseId") != "M3":
            problems.append(f"{where}: محور غير سليم {c.get('courseId')}")
        if c["chapter"] != chapters_ok[ci]:
            problems.append(f"{where}: اسم الفصل غير مطابق للجدول")
        scan(c["title"], f"{where} العنوان")
        expl = c["explanation"]
        scan(expl, f"{where} الشرح")
        n_sent = expl.count(".")
        if not (4 <= n_sent <= 6):
            problems.append(f"{where}: جمل الشرح {n_sent} خارج النطاق من أربع إلى ست")
        if len(expl) < 250:
            problems.append(f"{where}: شرح أقصر من الحد الأدنى {len(expl)}")
        if len(expl) < min_expl[0]:
            min_expl = (len(expl), where)
        if expl in seen_expl:
            problems.append(f"{where}: شرح مكرر حرفيًّا")
        seen_expl.add(expl)
        for part in expl.split("."):
            s = part.strip()
            if len(s) >= 30:
                if s in seen_sentences:
                    problems.append(f"{where}: جملة كاملة مكررة في الشرح «{s[:40]}»")
                seen_sentences.add(s)
        exs = c["examples"]
        if len(exs) != 5:
            problems.append(f"{where}: عدد الشواهد {len(exs)} غير الخمسة")
        for i, ex in enumerate(exs, 1):
            scan(ex, f"{where} شاهد {i}")
            if len(ex) < 60:
                problems.append(f"{where}: شاهد {i} أقصر من الحد الأدنى {len(ex)}")
            if len(ex) < min_example[0]:
                min_example = (len(ex), f"{where} شاهد {i}")
            if ex in seen_examples:
                problems.append(f"{where}: شاهد {i} مكرر حرفيًّا مع مفهوم آخر")
            seen_examples.add(ex)
        summ = c["example"]
        scan(summ, f"{where} الخلاصة")
        if not (30 <= len(summ) <= 130):
            problems.append(f"{where}: طول الخلاصة {len(summ)} خارج الحدود من ثلاثين إلى مئة وثلاثين")
        if summ in seen_summary:
            problems.append(f"{where}: خلاصة مكررة حرفيًّا")
        seen_summary.add(summ)

    # فحص الأسئلة
    by_concept: dict = {}
    seen_questions: set = set()
    seen_reasons: set = set()
    min_reason = (huge, "")
    tf_true = tf_false = 0
    diff_counts = {"سهل": 0, "متوسط": 0, "صعب": 0}
    ratio_worst = (0.0, "")
    for q in QUESTIONS:
        where = q["id"]
        scan(q["question"], f"{where} نص السؤال")
        reason = q.get("reason", "")
        scan(reason, f"{where} التعليل")
        if q["question"] in seen_questions:
            problems.append(f"{where}: نص سؤال مكرر حرفيًّا")
        seen_questions.add(q["question"])
        for part in q["question"].split("."):
            s = part.strip()
            if len(s) >= 30:
                if s in seen_sentences:
                    problems.append(f"{where}: جملة كاملة مكررة «{s[:40]}»")
                seen_sentences.add(s)
        if len(reason) < 150:
            problems.append(f"{where}: تعليل أقصر من الحد الأدنى {len(reason)}")
        if len(reason) < min_reason[0]:
            min_reason = (len(reason), where)
        if reason in seen_reasons:
            problems.append(f"{where}: تعليل مكرر حرفيًّا")
        seen_reasons.add(reason)
        for part in reason.split("."):
            s = part.strip()
            if len(s) >= 30:
                if s in seen_sentences:
                    problems.append(f"{where}: جملة كاملة مكررة في التعليل «{s[:40]}»")
                seen_sentences.add(s)
        if q["difficulty"] in diff_counts:
            diff_counts[q["difficulty"]] += 1
        else:
            problems.append(f"{where}: صعوبة غير معروفة {q['difficulty']}")
        opts = q["options"]
        correct_opts = [o for o in opts if o["isCorrect"]]
        if len(correct_opts) != 1:
            problems.append(f"{where}: عدد الخيارات الصحيحة {len(correct_opts)}")
        if q["type"] == "mcq":
            if len(opts) != 4:
                problems.append(f"{where}: خيارات {len(opts)} غير الأربعة")
            for o in opts:
                scan(o["text"], f"{where} خيار")
                if len(o["text"]) < 12:
                    problems.append(f"{where}: خيار قصير جدًّا «{o['text']}»")
            if correct_opts:
                corr_len = len(correct_opts[0]["text"])
                alts = [len(o["text"]) for o in opts if not o["isCorrect"]]
                avg_alt = sum(alts) / len(alts) if alts else 1
                ratio = corr_len / avg_alt
                if ratio > 1.4:
                    problems.append(f"{where}: انحياز طولي {ratio:.2f}")
                if ratio > ratio_worst[0]:
                    ratio_worst = (ratio, where)
                if q.get("correct") != correct_opts[0]["text"]:
                    problems.append(f"{where}: حقل correct لا يطابق الخيار الصحيح")
        elif q["type"] == "tf":
            if len(opts) != 2:
                problems.append(f"{where}: خيارات {len(opts)} غير الاثنين")
            if [o["text"] for o in opts] != ["صح", "خطأ"]:
                problems.append(f"{where}: خيارات صح/خطأ غير منضبطة")
            if q.get("correct") not in ("صح", "خطأ"):
                problems.append(f"{where}: قيمة correct غير سليمة")
            elif correct_opts and correct_opts[0]["text"] != q["correct"]:
                problems.append(f"{where}: correct لا يطابق الخيار الصحيح")
            if q.get("correct") == "صح":
                tf_true += 1
            elif q.get("correct") == "خطأ":
                tf_false += 1
        else:
            problems.append(f"{where}: نوع غير معروف {q['type']}")
        by_concept.setdefault(q["conceptId"], []).append(q)

    # أربعة أسئلة لكل مفهوم بالنمط: اختيار من متعدد ثم اختيار ثم صح/خطأ ثم صح/خطأ
    for c in CONCEPTS:
        qs = by_concept.get(c["id"], [])
        if [q["type"] for q in qs] != ["mcq", "mcq", "tf", "tf"]:
            problems.append(f"مفهوم {c['id']}: نمط الأسئلة غير مطابق للنمط المطلوب")
