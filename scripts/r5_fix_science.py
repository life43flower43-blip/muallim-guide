def replace_reason(qid, old, new):
    t = Q[qid]['reason']
    assert old in t, f'{qid} reason: لا يوجد: {old[:50]}'
    Q[qid]['reason'] = t.replace(old, new, 1)
    log.append(f'{qid}[reason]: {old[:55]}… → {new[:55]}…')

def replace_question(qid, old, new):
    t = Q[qid]['question']
    assert old in t, f'{qid} question: لا يوجد: {old[:50]}'
