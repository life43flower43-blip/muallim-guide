# ============================ SELF-CHECK ============================
def _self_check():
    from collections import Counter, defaultdict
    import re

    errors = []

    # 1) العدد الكلي
    if len(NEW_CONCEPTS) != 32:
        errors.append(f"عدد المفاهيم {len(NEW_CONCEPTS)} وليس 32")
    if len(QUESTIONS) != 64:
        errors.append(f"عدد الأسئلة {len(QUESTIONS)} وليس 64")

    # 2) التفرد: المعرفات وأسماء المفاهيم ونصوص الأسئلة
    cids = [c["cid"] for c in NEW_CONCEPTS]
    if len(set(cids)) != len(cids):
        errors.append("معرّف مفهوم مكرر")
    names = [c["name"] for c in NEW_CONCEPTS]
    if len(set(names)) != len(names):
        errors.append("اسم مفهوم مكرر")
    qtexts = [q["question"] for q in QUESTIONS]
    if len(set(qtexts)) != len(qtexts):
        errors.append("نص سؤال مكرر")

    # 3) البنية: مساقان وفصول بالأعداد المطلوبة
    courses = Counter(c["course"] for c in NEW_CONCEPTS)
    if courses.get("M2") != 20 or courses.get("M4") != 12:
        errors.append(f"توزيع المساقات خاطئ: {dict(courses)} (المطلوب M2=20 وM4=12)")
    expected_chapters = {
        ("M2", "الغرائز"): 7,
        ("M2", "العواطف والانفعالات"): 7,
        ("M2", "الذكاء"): 6,
        ("M4", "أسس القياس"): 4,
        ("M4", "أدوات التقويم"): 4,
        ("M4", "أنواع الاختبارات وخصائصها"): 4,
    }
    actual_chapters = Counter((c["course"], c["chapter"]) for c in NEW_CONCEPTS)
    for key, want in expected_chapters.items():
        if actual_chapters.get(key, 0) != want:
            errors.append(f"فصل «{key[1]}» في {key[0]} عدده {actual_chapters.get(key, 0)} والمطلوب {want}")

    # 4) الأطوال الدنيا
    for c in NEW_CONCEPTS:
        if len(c["explanation"]) < 120:
            errors.append(f"explanation قصير ({len(c['explanation'])} حرفاً): {c['cid']}")
        if len(c["example"]) < 100:
            errors.append(f"example قصير ({len(c['example'])} حرفاً): {c['cid']}")

    # 5) لكل مفهوم سؤالان بالضبط: mcq + tf بنصين مختلفين
    qmap = defaultdict(list)
    for q in QUESTIONS:
        qmap[q["cid"]].append(q)
    for c in NEW_CONCEPTS:
        qs = qmap.get(c["cid"], [])
        types = sorted(q["qtype"] for q in qs)
        if types != ["mcq", "tf"]:
            errors.append(f"{c['cid']}: أنواع الأسئلة {types} والمطلوب mcq+tf بالضبط")
        if len({q["question"] for q in qs}) != len(qs):
            errors.append(f"{c['cid']}: نصّا السؤالين متطابقان")

    # 6) تحقق كل سؤال
    cidset = set(cids)
    for q in QUESTIONS:
        head = q["question"][:34]
        if q["cid"] not in cidset:
            errors.append(f"سؤال لمفهوم غير موجود: {q['cid']}")
        if q["diff"] not in ("سهل", "متوسط", "صعب"):
            errors.append(f"صعوبة غير معروفة: {head}")
        if len(q["reason"]) < 150:
            errors.append(f"reason قصيرة ({len(q['reason'])} حرفاً): {head}")
        if q["qtype"] == "mcq":
            opts = [q[k] for k in ("a", "b", "c", "d")]
            if len(set(opts)) != 4:
                errors.append(f"خيارات mcq غير رباعية مميزة تماماً: {head}")
            if q["correct"] not in opts:
                errors.append(f"correct ليس النص الحرفي لأحد الخيارات: {head}")
        elif q["qtype"] == "tf":
            if q.get("a") != "صح" or q.get("b") != "خطأ":
                errors.append(f"tf خياراته غير قياسية (صح/خطأ): {head}")
            if q["correct"] not in ("صح", "خطأ"):
                errors.append(f"tf correct غير صالح: {head}")
        else:
            errors.append(f"نوع سؤال غير معروف: {head}")

    # 7) توازن صح/خطأ تقريباً نصف/نصف
    tf_all = [q for q in QUESTIONS if q["qtype"] == "tf"]
    tf_true = sum(1 for q in tf_all if q["correct"] == "صح")
    tf_false = len(tf_all) - tf_true
    if abs(tf_true - tf_false) > 2:
        errors.append(f"عدم توازن صح/خطأ: {tf_true} صح مقابل {tf_false} خطأ")

    # 8) لا حروف لاتينية داخل نصوص المحتوى (المعرّفات والمساقات استثناء)
    latin = re.compile(r"[A-Za-z]")
    for c in NEW_CONCEPTS:
        for k in ("name", "chapter", "explanation", "example"):
            if latin.search(c[k]):
                errors.append(f"حروف لاتينية في {c['cid']} ({k})")
    for q in QUESTIONS:
        for k in ("question", "a", "b", "correct", "reason"):
            if latin.search(str(q[k])):
                errors.append(f"حروف لاتينية في سؤال: {q['question'][:30]}")

    # 9) توزيع الصعوبة المستهدف: 16 سهل / 35 متوسط / 13 صعب
    dist = Counter(q["diff"] for q in QUESTIONS)
    target = {"سهل": 16, "متوسط": 35, "صعب": 13}
    for d, want in target.items():
        if dist.get(d, 0) != want:
            errors.append(f"توزيع الصعوبة: «{d}» عددها {dist.get(d, 0)} والمطلوب {want}")

    if errors:
        print("SELF-CHECK FAILED —", len(errors), "خطأ:")
        for e in errors[:40]:
            print(" -", e)
        raise RuntimeError("فشل الفحص الذاتي لملف rgen_w2.py")

    print("SELF-CHECK OK")
    print(f"المفاهيم: {len(NEW_CONCEPTS)} (M2: {courses['M2']} | M4: {courses['M4']})")
    print(f"الأسئلة: {len(QUESTIONS)} (mcq: 32 | tf: 32) — صح/خطأ: {tf_true}/{tf_false}")
    print(f"توزيع الصعوبة: سهل {dist['سهل']} | متوسط {dist['متوسط']} | صعب {dist['صعب']}")


_self_check()
