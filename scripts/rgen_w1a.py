# ============================ SELF-CHECK ============================

def _count_sentences(text):
    return len([p for p in text.split(".") if p.strip()])


def _has_latin(text):
    return any(("a" <= ch <= "z") or ("A" <= ch <= "Z") for ch in text)


def run_self_check():
    from collections import Counter

    errors = []

    # --- 1) المفاهيم: العدد والأسماء بالترتيب والتفرّد ---
    if len(NEW_CONCEPTS) != 12:
        errors.append("عدد المفاهيم = %d والمطلوب 12" % len(NEW_CONCEPTS))
    names = [c.get("name", "") for c in NEW_CONCEPTS]
    if len(set(names)) != len(names):
        errors.append("تكرار في أسماء المفاهيم")
    if names != REQUIRED_CONCEPT_NAMES:
        for i in range(max(len(names), len(REQUIRED_CONCEPT_NAMES))):
            got = names[i] if i < len(names) else "<غير موجود>"
            want = REQUIRED_CONCEPT_NAMES[i] if i < len(REQUIRED_CONCEPT_NAMES) else "<غير موجود>"
            if got != want:
                errors.append("ترتيب المفاهيم مختل: المفهوم رقم %d هو «%s» والمطلوب «%s»" % (i + 1, got, want))
    cids = [c.get("cid", "") for c in NEW_CONCEPTS]
    if len(set(cids)) != len(cids):
        errors.append("تكرار في معرفات المفاهيم")

    # --- 2) أطوال الشرح والمثال وعدد الجمل وعدم وجود حروف لاتينية ---
    seen_expl, seen_exam = set(), set()
    for c in NEW_CONCEPTS:
        expl = c.get("explanation", "")
        exam = c.get("example", "")
        if len(expl) < 120:
            errors.append("شرح المفهوم %s قصير: %d حرفاً (< 120)" % (c.get("cid"), len(expl)))
        sc = _count_sentences(expl)
        if not (3 <= sc <= 4):
            errors.append("شرح المفهوم %s خارج نطاق 3-4 جمل: %d" % (c.get("cid"), sc))
        if len(exam) < 100:
            errors.append("مثال المفهوم %s قصير: %d حرفاً (< 100)" % (c.get("cid"), len(exam)))
        if expl in seen_expl:
            errors.append("تكرار نص شرح في المفهوم %s" % c.get("cid"))
        seen_expl.add(expl)
        if exam in seen_exam:
            errors.append("تكرار نص مثال في المفهوم %s" % c.get("cid"))
        seen_exam.add(exam)
        for f in ("name", "explanation", "example"):
            if _has_latin(c.get(f, "")):
                errors.append("حروف لاتينية في حقل %s للمفهوم %s" % (f, c.get("cid")))

    # --- 3) الأسئلة: العدد والتغطية والخيارات والإجابات والأطوال والتفرّد ---
    if len(QUESTIONS) != 24:
        errors.append("عدد الأسئلة = %d والمطلوب 24" % len(QUESTIONS))
    diff_counter = Counter()
    tf_counter = Counter()
    per_concept = {c["cid"]: Counter() for c in NEW_CONCEPTS}
    seen_questions, seen_reasons, seen_mcq_options = set(), set(), set()
    for q in QUESTIONS:
        cid = q.get("cid")
        qtype = q.get("qtype")
        diff = q.get("diff")
        if cid not in per_concept:
            errors.append("سؤال بمعرف مفهوم غير معروف: %s" % cid)
            continue
        if qtype not in ("mcq", "tf"):
            errors.append("نوع سؤال غير صحيح عند المفهوم %s: %s" % (cid, qtype))
            continue
        per_concept[cid][qtype] += 1
        if diff not in ("سهل", "متوسط", "صعب"):
            errors.append("صعوبة غير معروفة عند المفهوم %s: %s" % (cid, diff))
        else:
            diff_counter[diff] += 1

        qtext = q.get("question", "")
        if len(qtext) < 40:
            errors.append("نص السؤال قصير عند المفهوم %s (%s): %d" % (cid, qtype, len(qtext)))
        if qtext in seen_questions:
            errors.append("تكرار نص سؤال عند المفهوم %s (%s)" % (cid, qtype))
        seen_questions.add(qtext)

        reason = q.get("reason", "")
        if len(reason) < 150:
            errors.append("سبب الإجابة قصير عند المفهوم %s (%s): %d < 150" % (cid, qtype, len(reason)))
        if reason in seen_reasons:
            errors.append("تكرار نص سبب الإجابة عند المفهوم %s (%s)" % (cid, qtype))
        seen_reasons.add(reason)
        if _has_latin(qtext) or _has_latin(reason):
            errors.append("حروف لاتينية في نص السؤال أو السبب عند المفهوم %s (%s)" % (cid, qtype))

        if qtype == "mcq":
            opts = [q.get("a", ""), q.get("b", ""), q.get("c", ""), q.get("d", "")]
            if len(set(opts)) != 4:
                errors.append("خيارات غير مختلفة تماماً في سؤال mcq للمفهوم %s" % cid)
            if q.get("correct") not in opts:
                errors.append("الإجابة الصحيحة ليست ضمن الخيارات في سؤال mcq للمفهوم %s" % cid)
            for o in opts:
                if _has_latin(o):
                    errors.append("حروف لاتينية في خيار عند المفهوم %s" % cid)
                if o in seen_mcq_options:
                    errors.append("تكرار نص خيار بين الأسئلة: %s" % o[:30])
                seen_mcq_options.add(o)
        else:  # tf
            if q.get("a") != "صح" or q.get("b") != "خطأ":
                errors.append("خيارات صح/خطأ غير معيارية في سؤال tf للمفهوم %s" % cid)
            if q.get("correct") not in ("صح", "خطأ"):
                errors.append("الإجابة الصحيحة في سؤال tf للمفهوم %s ليست صح أو خطأ" % cid)
            tf_counter[q.get("correct")] += 1

    # --- 4) تغطية المفاهيم: mcq واحد + tf واحد لكل مفهوم ---
    for c in NEW_CONCEPTS:
        cnt = per_concept[c["cid"]]
        if cnt["mcq"] != 1 or cnt["tf"] != 1:
            errors.append("المفهوم %s يجب أن يكون له سؤال mcq واحد وسؤال tf واحد (الموجود: mcq=%d, tf=%d)"
                          % (c["cid"], cnt["mcq"], cnt["tf"]))

    # --- 5) توزيع الصعوبة والتوازن بين صح/خطأ ---
    for d, want in (("سهل", 6), ("متوسط", 13), ("صعب", 5)):
        got = diff_counter.get(d, 0)
        if got != want:
            errors.append("توزيع الصعوبة: %s = %d والمطلوب %d" % (d, got, want))
    if tf_counter.get("صح", 0) != 6 or tf_counter.get("خطأ", 0) != 6:
        errors.append("توزيع إجابات صح/خطأ = صح:%d وخطأ:%d والمطلوب 6/6"
                      % (tf_counter.get("صح", 0), tf_counter.get("خطأ", 0)))

    if errors:
        print("SELF-CHECK FAILED — عدد الأخطاء: %d" % len(errors))
        for e in errors:
            print(" -", e)
        raise RuntimeError("فشل الفحص الذاتي لملف rgen_w1a.py: %d خطأ" % len(errors))

    print("SELF-CHECK OK")
    print("المفاهيم: 12 | الأسئلة: 24 (12 mcq + 12 tf) | المفهوم الواحد: 1 mcq + 1 tf")
    print("توزيع الصعوبة: سهل=6، متوسط=13، صعب=5")
    print("إجابات صح/خطأ: صح=6، خطأ=6")


if __name__ == "__main__":
    run_self_check()
