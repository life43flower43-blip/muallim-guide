    # إعادة التحميل والتحقق مجدداً من الملف المكتوب فعلاً
    with open(OUT, encoding="utf-8") as f:
        reloaded = json.load(f)

    errs2 = check(reloaded, "فحص بعد json.load")
    if errs2:
        for e in errs2:
            print("خطأ بعد التحميل:", e)
        sys.exit(1)

    print("SELF-CHECK OK →", OUT)


