# ------------------------------------------------------------- التحقق الذاتي ---
def wc(s):
    return len(s.split())

def sc(s):
    return len([x for x in re.split(r"[.!؟]", s) if x.strip()])

TEXT_KEYS = []

def texts_of(q):
    t = [q["question"], q["correct"], q["reason"]]
    t += [o["text"] for o in q["options"]]
    return t

def check(data, label):
    errs = []
    concepts, questions = data["concepts"], data["questions"]

    if data.get("chapter") != CHAPTER:
        errs.append("الفقرة العلوية chapter غير صحيحة")

    ids = [c["id"] for c in concepts]
    if sorted(ids) != sorted({f"P{n}" for n in range(301, 311)}):
        errs.append("معرفات المفاهيم ليست P301..P310 كما يجب: %s" % ids)
    if len(set(ids)) != len(ids):
        errs.append("تكرار في معرفات المفاهيم")
    if len(set(c["title"] for c in concepts)) != len(concepts):
        errs.append("تكرار في عناوين المفاهيم")

    for c in concepts:
        if c["courseId"] != COURSE or c["chapter"] != CHAPTER:
            errs.append("%s: courseId/chapter غير صحيحة" % c["id"])
        w, s = wc(c["explanation"]), sc(c["explanation"])
        if not (100 <= w <= 160):
            errs.append("%s: شرح %d كلمة (المطلوب ١٠٠-١٦٠)" % (c["id"], w))
        if not (3 <= s <= 5):
            errs.append("%s: شرح %d جملة (المطلوب ٣-٥)" % (c["id"], s))
        if len(c["examples"]) != 2:
            errs.append("%s: الأمثلة ليست قصتين" % c["id"])
        for i, ex in enumerate(c["examples"], 1):
            w = wc(ex)
            if not (30 <= w <= 60):
                errs.append("%s: المثال %d يحوي %d كلمة (المطلوب ٣٠-٦٠)" % (c["id"], i, w))

    if not (35 <= len(questions) <= 40):
        errs.append("عدد الأسئلة %d خارج المدى ٣٥-٤٠" % len(questions))

    seen_q, seen_qt = set(), set()
    per_concept = {}
    diff_count = {"سهل": 0, "متوسط": 0, "صعب": 0}
    type_count = {"mcq": 0, "tf": 0}

    for q in questions:
        tag = q["id"]
        if tag in seen_q:
            errs.append("تكرار معرف السؤال %s" % tag)
        seen_q.add(tag)
        if not re.fullmatch(r"QP3\d\d-\d", tag):
            errs.append("معرف السؤال %s لا يطابق النمط" % tag)
        if q["conceptId"] not in ids:
            errs.append("%s: conceptId غير موجود (%s)" % (tag, q["conceptId"]))
        per_concept[q["conceptId"]] = per_concept.get(q["conceptId"], 0) + 1
        if q["type"] not in ("mcq", "tf"):
            errs.append("%s: نوع غير معروف" % tag)
        else:
            type_count[q["type"]] += 1
        if q["difficulty"] not in ("سهل", "متوسط", "صعب"):
            errs.append("%s: صعوبة غير معروفة" % tag)
        else:
            diff_count[q["difficulty"]] += 1
        if q["fixedOrder"] is not True:
            errs.append("%s: fixedOrder ليس true" % tag)
        if q["question"] in seen_qt:
            errs.append("تكرار نص السؤال %s" % tag)
        seen_qt.add(q["question"])

        n = len(q["options"])
        expected = 4 if q["type"] == "mcq" else 2
        if n != expected:
            errs.append("%s: عدد الخيارات %d (المطلوب %d)" % (tag, n, expected))
        corr = [o for o in q["options"] if o["isCorrect"] is True]
        if len(corr) != 1:
            errs.append("%s: عدد isCorrect الصحيح %d" % (tag, len(corr)))
        elif corr[0]["text"] != q["correct"]:
            errs.append("%s: correct لا يطابق نص الخيار الصحيح حرفياً" % tag)
        for o in q["options"]:
            if not isinstance(o["isCorrect"], bool):
                errs.append("%s: isCorrect ليس منطقياً" % tag)

        wr = wc(q["reason"])
        if not (40 <= wr <= 90):
            errs.append("%s: reason %d كلمة (المطلوب ٤٠-٩٠)" % (tag, wr))

        # لغة: لا لاتيني ولا أرقام لاتينية، ولا عبارات محظورة
        blob = " ".join(texts_of(q))
        if re.search(r"[A-Za-z]", blob):
            errs.append("%s: حروف لاتينية داخل نص المحتوى" % tag)
        if re.search(r"[0-9]", blob):
            errs.append("%s: أرقام لاتينية داخل نص المحتوى" % tag)
        if "جميع ما سبق" in blob or "لا شيء مما سبق" in blob:
            errs.append("%s: عبارة محظورة" % tag)

    for c in concepts:
        blob = c["title"] + " " + c["explanation"] + " " + " ".join(c["examples"])
        if re.search(r"[A-Za-z]", blob) or re.search(r"[0-9]", blob):
            errs.append("%s: لاتيني أو أرقام لاتينية داخل المفهوم" % c["id"])

    for cid, cnt in per_concept.items():
        if not (3 <= cnt <= 4):
            errs.append("%s: عدد أسئلته %d خارج ٣-٤" % (cid, cnt))
    if len(per_concept) != 10:
        errs.append("ليست كل المفاهيم مغطاة بأسئلة")

    print("[%s] مفاهيم: %d | أسئلة: %d | أنواع: %s | صعوبة: %s" %
          (label, len(concepts), len(questions), type_count, diff_count))
    for cid in sorted(per_concept):
        print("   %s: %d أسئلة" % (cid, per_concept[cid]))
    return errs


def main():
    data = {"chapter": CHAPTER, "concepts": CONCEPTS, "questions": QUESTIONS}

