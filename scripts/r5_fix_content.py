#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
إصلاحات محتوى (مرحلة 6):
- Q708: من ثنائية وراثي/غير وراثي مبسطة إلى التقييم الفردي للاحتياجات (جولة 8 و12 من المراجع)
- Q1167: إعادة بناء سيناريو القضم — بلا ادعاء غريزة قاطعة، مع التحقق من السبب والسلامة (جولة 2)
"""
import json

BANK = 'public/data/qbank.json'
d = json.load(open(BANK, encoding='utf-8'))
Q = {q['id']: q for q in d['questions']}
log = []

# ═══ Q708 ═══
q = Q['Q708']
q['question'] = ('تعاني طالبتان صعوبات في القراءة والكتابة، وبيّن التشخيص أن إحداهما لديها حالة صحية '
                 'موثقة تحتاج متابعة طبية، والأخرى صعوبة تعلم بلا حالة صحية مصاحبة. على أي أساس يُبنى '
                 'التدخل التربوي الأنسب لكل منهما؟')
q['options'] = [
    {'text': 'على تقييم الاحتياجات الفردية الموثقة لكل طالبة: تكييفات تربوية للجميع، مع تنسيق المتابعة الصحية لمن لها حالة موثقة', 'isCorrect': True},
    {'text': 'على نوع السبب وحده: وراثي فالتدخل طبي فقط، وغير وراثي فتربوي فقط', 'isCorrect': False},
    {'text': 'على تفضيل المعلمة وخبرتها السابقة مع كل حالة', 'isCorrect': False},
    {'text': 'على تشابه الأعراض الظاهرة: متشابهتا المظهر تتلقيان الخطة ذاتها بلا تقييم فردي', 'isCorrect': False},
]
q['correct'] = q['options'][0]['text']
q['reason'] = ('الأساس المنهجي للتدخل هو التقييم الفردي للاحتياجات: فالحالة الصحية الموثقة تستدعي تنسيقاً مع '
               'المتابعة الطبية ضمن خطة تربوية لا بديلاً عنها، وصعوبة التعلم بلا حالة صحية تحتاج هي الأخرى '
               'تقييماً واستراتيجيات خاصة. أما ربط نوع التدخل بالسبب الوراثي وحده أو بالأعراض الظاهرة أو بتفضيل '
               'المعلمة فافتراضات تسبق التقييم وتضيّق الخدمة المطلوبة.')
if not q.get('fixedOrder'):
    q['fixedOrder'] = True
log.append('Q708: إعادة بناء (التقييم الفردي بدل ثنائية وراثي/غير وراثي)')

# ═══ Q1167 ═══
q = Q['Q1167']
q['question'] = ('تلاحظ المعلمة سارة أن طفل الروضة ريان يقضم الألواح الخشبية باستمرار. تحققت من سلامته ومن أن '
                 'السلوك غير مؤذٍ، ثم جهزت له بدائل آمنة مخصصة للقضم مع متابعة سبب السلوك والتواصل مع الأسرة '
                 'عند الحاجة. أي التصرفات التالية أقرب إلى الممارسة المهنية السليمة؟')
q['options'] = [
    {'text': 'توجيه الحاجة الحسية الفمية إلى بدائل آمنة بعد التحقق من سلامة الطفل ورصد سبب السلوك', 'isCorrect': True},
    {'text': 'المنع الفوري المتكرر للقضم لأنه سلوك مزعج ولا يُبحث عن خلفه', 'isCorrect': False},
    {'text': 'تجاهل السلوك تماماً لأن سلوكيات هذا العمر تزول وحدها دائماً', 'isCorrect': False},
    {'text': 'الاكتفاء بتوفير البدائل الآمنة دون فحص سبب السلوك أو متابعته', 'isCorrect': False},
]
q['correct'] = q['options'][0]['text']
q['reason'] = ('الممارسة السليمة تلبي الحاجة الحسية المفترضة ببدائل آمنة بعد التحقق من سلامة الطفل، وتتابع السلوك '
               'وأسبابه المحتملة — حسيّة أو نمائية أو انفعالية — مع التواصل مع الأسرة عند الحاجة. فالقضم لا يثبت '
               'بذاته غريزة محددة، وتوفير البدائل وحده لا يغني عن فحص السبب. أما بقية الخيارات فمنع قاسٍ بلا '
               'استقصاء، أو إهمال، أو رضا ناقص بالتدخل.')
if not q.get('fixedOrder'):
    q['fixedOrder'] = True
log.append('Q1167: إعادة بناء (بلا ادعاء غريزة قاطعة + فحص السبب والسلامة)')

json.dump(d, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False)
with open('review/r5_content_log.md', 'w', encoding='utf-8') as f:
    f.write('# سجل إصلاحات المحتوى (مرحلة 6)\n\n')
    for line in log:
        f.write(f'- {line}\n')
print(f'أُنجز {len(log)} إصلاحًا.')
