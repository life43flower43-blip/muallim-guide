def main():
    with open(POOL, encoding='utf-8') as f:
        pool = {q['id']: q for q in json.load(f)}
    with open(IDS, encoding='utf-8') as f:
        ids = json.load(f)

    missing = [i for i in ids if i not in pool]
    if missing:
        raise SystemExit('IDs missing from pool: %r' % missing)
    if set(WRONG) != set(ids) or len(WRONG) != len(ids):
        raise SystemExit('WRONG keys must equal ids list exactly')

    patches = []
    for qid in ids:
        opts = pool[qid]['options']
        ci = [k for k, o in enumerate(opts) if o['isCorrect']]
        if len(ci) != 1:
            raise SystemExit('%s: pool must have exactly one correct option' % qid)
        ci = ci[0]
        wrongs = WRONG[qid]
        if len(wrongs) != 3:
            raise SystemExit('%s: need exactly three wrong rewrites' % qid)
        new_opts, wi = [], 0
        for k, o in enumerate(opts):
            if k == ci:
                new_opts.append({'text': o['text'], 'isCorrect': True})
            else:
                new_opts.append({'text': wrongs[wi], 'isCorrect': False})
                wi += 1
        patches.append({'id': qid, 'options': new_opts})

    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump({'patches': patches}, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('WROTE %s : %d patches' % (OUT, len(patches)))
    # معاينة الأطوال
    with open(OUT, encoding='utf-8') as f:
        data = json.load(f)
    for p in data['patches']:
        lens = [len(o['text']) for o in p['options']]
        ci = [k for k, o in enumerate(p['options']) if o['isCorrect']][0]
        L = lens[ci]
        ratios = ['%.0f%%' % (100.0 * lens[k] / L) for k in range(4) if k != ci]
        print(p['id'], 'correctIdx', ci, 'L', L, 'wrongRatios', ratios)

if __name__ == '__main__':
    main()
