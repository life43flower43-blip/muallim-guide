if __name__ == "__main__":
    import re

    errors = []
    EXPECTED_CHAPTERS = ["ط. التعليم الأساسي", "ي. التعليم الثانوي", "ك. التعليم الحكومي"]
    EXPECTED_COUNTS = {CH_BASIC: 10, CH_SEC: 8, CH_GOV: 7}

    # 1) عدد المفاهيم
    if len(NEW_CONCEPTS) != 25:
        errors.append("عدد المفاهيم = " + str(len(NEW_CONCEPTS)) + " بدل 25")

    # 2) عدد الأسئلة
    if len(QUESTIONS) != 50:
        errors.append("عدد الأسئلة = " + str(len(QUESTIONS)) + " بدل 50")

    # 3) أسماء الفصول الثلاثة حرفية وعدد المفاهيم لكل فصل
    per_ch = {ch: 0 for ch in EXPECTED_CHAPTERS}
    for c in NEW_CONCEPTS:
        if c["chapter"] not in per_ch:
            errors.append("فصل غير حرفي أو غير معتمد: " + c["chapter"])
        else:
            per_ch[c["chapter"]] += 1
    for ch in EXPECTED_CHAPTERS:
        if per_ch[ch] != EXPECTED_COUNTS[ch]:
            errors.append("عدد مفاهيم فصل «" + ch + "» = " + str(per_ch[ch]) + " بدل " + str(EXPECTED_COUNTS[ch]))

    # 4) course موحد G1
    for c in NEW_CONCEPTS:
        if c.get("course") != "G1":
            errors.append(c.get("cid", "?") + ": course يجب أن يكون G1")

    # 5) لكل مفهوم سؤالان بالضبط: 1 mcq + 1 tf، وcorrect ضمن الخيارات
    by_cid = {}
    for q in QUESTIONS:
        by_cid.setdefault(q["cid"], []).append(q)
    cids = {c["cid"] for c in NEW_CONCEPTS}
    for q in QUESTIONS:
        if q["cid"] not in cids:
            errors.append("سؤال بمفهوم غير موجود: " + q["cid"])
    for c in NEW_CONCEPTS:
        qs = by_cid.get(c["cid"], [])
        types = sorted(q["qtype"] for q in qs)
        if types != ["mcq", "tf"]:
            errors.append(c["cid"] + ": أنواع الأسئلة " + str(types) + " بدل [mcq, tf]")
        for q in qs:
            if q["qtype"] == "mcq":
                opts = [q["a"], q["b"], q["c"], q["d"]]
                if len(set(opts)) != 4:
                    errors.append(c["cid"] + " mcq: الخيارات الأربعة ليست مختلفة تماماً")
                if q["correct"] not in opts:
                    errors.append(c["cid"] + " mcq: correct ليس النص الحرفي لأحد الخيارات")
            elif q["qtype"] == "tf":
                if q["a"] != "صح" or q["b"] != "خطأ":
                    errors.append(c["cid"] + " tf: يجب أن تكون a=صح وb=خطأ")
                if q["correct"] not in ("صح", "خطأ"):
                    errors.append(c["cid"] + " tf: correct غير صالح")
            else:
                errors.append(c["cid"] + ": نوع سؤال غير معروف: " + str(q["qtype"]))

    # 6) أطوال دنيا
    for c in NEW_CONCEPTS:
        if len(c["explanation"]) < 120:
            errors.append(c["cid"] + ": explanation أقصر من 120 حرفاً")
        if len(c["example"]) < 100:
            errors.append(c["cid"] + ": example أقصر من 100 حرف")
    for q in QUESTIONS:
        if len(q["reason"]) < 150:
            errors.append(q["cid"] + " (" + q["qtype"] + "): reason أقصر من 150 حرفاً")

    # 7) التفرد (لا تكرار نصوص)
    def uniq_check(seq, label):
        if len(set(seq)) != len(seq):
            errors.append("تكرار في " + label)

    uniq_check([c["cid"] for c in NEW_CONCEPTS], "معرفات المفاهيم")
    uniq_check([c["name"] for c in NEW_CONCEPTS], "أسماء المفاهيم")
    uniq_check([c["explanation"] for c in NEW_CONCEPTS], "الشروح")
    uniq_check([c["example"] for c in NEW_CONCEPTS], "الأمثلة")
    uniq_check([q["question"] for q in QUESTIONS], "نصوص الأسئلة")
    uniq_check([q["reason"] for q in QUESTIONS], "أسباب الإجابة")

    # 8) توزيع الصعوبة: 12 سهل / 28 متوسط / 10 صعب
    diffs = {"سهل": 0, "متوسط": 0, "صعب": 0}
    for q in QUESTIONS:
        if q["diff"] not in diffs:
            errors.append(q["cid"] + ": قيمة صعوبة غير معروفة: " + q["diff"])
        else:
            diffs[q["diff"]] += 1
    if (diffs["سهل"], diffs["متوسط"], diffs["صعب"]) != (12, 28, 10):
        errors.append("توزيع الصعوبة غير مطابق: " + str(diffs))

    # 9) توازن صح/خطأ تقريباً نصف/نصف
    tfs = [q for q in QUESTIONS if q["qtype"] == "tf"]
    n_true = sum(1 for q in tfs if q["correct"] == "صح")
    n_false = len(tfs) - n_true
    if not (len(tfs) == 25 and 10 <= n_true <= 15 and 10 <= n_false <= 15):
        errors.append("عدم توازن صح/خطأ: " + str(n_true) + "/" + str(n_false))

    # 10) منع القالب الممنوع في الأسئلة
    for q in QUESTIONS:
        if "من المفاهيم" in q["question"] or q["question"].startswith("يُعد"):
            errors.append(q["cid"] + " (" + q["qtype"] + "): سؤال على القالب الممنوع")

    # 11) نظافة النصوص من الحروف اللاتينية داخل الكلمات (TIMSS و PISA بين مسافات فقط)
    allowed_latin = {"TIMSS", "PISA"}

    def find_bad_latin(text):
        for tok in text.split():
            if re.search(r"[A-Za-z]", tok):
                core = tok[1:] if tok.startswith("و") else tok
                core = core.strip("()،.؛:")
                if core not in allowed_latin:
                    return tok
        return None

    prose_texts = []
    for c in NEW_CONCEPTS:
        prose_texts.extend([c["name"], c["explanation"], c["example"]])
    for q in QUESTIONS:
        prose_texts.extend([q["question"], q["a"], q["b"], q["reason"]])
        if q["qtype"] == "mcq":
            prose_texts.extend([q["c"], q["d"]])
    for t in prose_texts:
        bad = find_bad_latin(t)
        if bad:
            errors.append("كلمة تحتوي حروفاً لاتينية غير مسموحة: " + bad)

    if errors:
        print("SELF-CHECK FAILED")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)

    mcq_n = sum(1 for q in QUESTIONS if q["qtype"] == "mcq")
    tf_n = sum(1 for q in QUESTIONS if q["qtype"] == "tf")
    print("عدد المفاهيم:", len(NEW_CONCEPTS))
    print("توزيع الفصول:", {ch: per_ch[ch] for ch in EXPECTED_CHAPTERS})
    print("عدد الأسئلة:", len(QUESTIONS), "(mcq:", mcq_n, "/ tf:", tf_n, ")")
    print("توزيع الصعوبة: سهل =", diffs["سهل"], "/ متوسط =", diffs["متوسط"], "/ صعب =", diffs["صعب"])
    print("توازن صح/خطأ:", str(n_true) + "/" + str(n_false))
    print("SELF-CHECK OK")
