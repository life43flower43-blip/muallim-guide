"""إصلاح أكاديمي شامل للبنك: إعادة كتابة الأمثلة المكسورة نحوًا ومعنًى + أخطاء موضعية دقيقة."""
import json, sys

PATH = '/home/z/my-project/src/data/qbank.json'
d = json.load(open(PATH, encoding='utf-8'))
byc = {c['id']: c for c in d['concepts']}
byq = {q['id']: q for q in d['questions']}
log = []

def set_example(cid, idx, new_text):
    c = byc[cid]
    exs = c.get('examples')
    old = exs[idx]
    exs[idx] = new_text
    log.append(f'[مثال {cid}#{idx+1}] أعيد كتابته ({len(old)} → {len(new_text)} حرفًا)')

def patch_text(qid, field, old, new):
    q = byq[qid]
    t = str(q[field])
    assert old in t, f'لم يُعثر على النص في {qid}.{field}: {old[:40]}'
    q[field] = t.replace(old, new)
    log.append(f'[نص {qid}.{field}] «{old[:38]}…» → «{new[:38]}…»')

def patch_concept(cid, old, new):
    c = byc[cid]
    assert old in c['explanation'], f'لم يُعثر في شرح {cid}: {old[:40]}'
    c['explanation'] = c['explanation'].replace(old, new)
    log.append(f'[شرح {cid}] «{old[:38]}…» → «{new[:38]}…»')

def patch_example_frag(cid, idx, old, new):
    c = byc[cid]
    exs = c.get('examples')
    assert old in exs[idx], f'لم يُعثر في مثال {cid}#{idx}: {old[:40]}'
    exs[idx] = exs[idx].replace(old, new)
    log.append(f'[مثال {cid}#{idx+1}] «{old[:38]}…» → «{new[:38]}…»')

