# القصور اللاتيني «...» → الحذف العربي «…»
dots = 0
for c in d['concepts']:
    for i, ex in enumerate(c.get('examples') or []):
        if isinstance(ex, str) and '...' in ex:
            c['examples'][i] = ex.replace('...', '…'); dots += 1
    if '...' in c['explanation']:
        c['explanation'] = c['explanation'].replace('...', '…'); dots += 1
for q in d['questions']:
    for f in ('question', 'reason'):
        if '...' in str(q[f]):
            q[f] = str(q[f]).replace('...', '…'); dots += 1
    if isinstance(q['options'], list):
        for o in q['options']:
            if isinstance(o, dict) and '...' in str(o.get('text', '')):
                o['text'] = o['text'].replace('...', '…'); dots += 1
log.append(f'[ترقيم] استبدال الحذف اللاتيني «...» بالعربي «…» في {dots} موضعًا')

# ============ ٣. تحويل بدايات «ما هو/من هو» إلى صياغة أكاديمية مباشرة ============
mh = 0
for q in d['questions']:
    t = str(q['question'])
    if t.startswith('ما هو '):
        q['question'] = 'ما ' + t[6:]; mh += 1
    elif t.startswith('من هو '):
        q['question'] = 'من ' + t[6:]; mh += 1
log.append(f'[أسلوب] تحويل «ما هو/من هو» إلى الاستفهام المباشر في {mh} سؤالًا')

json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('\n'.join(log))
print(f'\nإجمالي الإصلاحات: {len(log)}')
