    qs_by_cid = defaultdict(list)
    for q in QUESTIONS:
        qs_by_cid[q.get("cid")].append(q)
    for c in NEW_CONCEPTS:
        qs = qs_by_cid.get(c["cid"], [])
        if len(qs) != 2:
            errors.append(f"{c['cid']} عدد أسئلته {len(qs)} والمطلوب 2")
            continue
        if sorted(q["qtype"] for q in qs) != ["mcq", "tf"]:
            errors.append(f"{c['cid']} لا يحوي mcq+tf بالضبط")
    cid_set = set(cids)
    for q in QUESTIONS:
        if q.get("cid") not in cid_set:
            errors.append(f"سؤال لمفهوم غير موجود: {q.get('cid')}")

    # 6) تفرّد نصوص الأسئلة
    qtexts = [q.get("question", "") for q in QUESTIONS]
    if len(set(qtexts)) != len(qtexts):
        dup = {t for t in qtexts if qtexts.count(t) > 1}
        errors.append(f"نصوص أسئلة مكررة: {list(dup)[:2]}")

    # 7) فحص كل سؤال
    for q in QUESTIONS:
        head = q.get("question", "")[:40]
        if q.get("qtype") == "mcq":
            opts = [q.get(k) for k in ("a", "b", "c", "d")]
            if any(not o for o in opts):
                errors.append(f"mcq خيار ناقص: {head}")
            elif len(set(opts)) != 4:
                errors.append(f"mcq خيارات متطابقة: {head}")
            if q.get("correct") not in opts:
                errors.append(f"correct ليس ضمن الخيارات: {head}")
        elif q.get("qtype") == "tf":
            if q.get("a") != "صح" or q.get("b") != "خطأ":
                errors.append(f"tf خياراته ليست صح/خطأ: {head}")
            if q.get("correct") not in ("صح", "خطأ"):
                errors.append(f"tf correct غير صالح: {head}")
            if q.get("c") or q.get("d"):
                errors.append(f"tf يحوي خيارات زائدة c/d: {head}")
        else:
            errors.append(f"qtype غير معروف: {q.get('qtype')} في {head}")
            continue
        if q.get("diff") not in ("سهل", "متوسط", "صعب"):
            errors.append(f"صعوبة غير صالحة: {head}")
        if len(q.get("reason", "")) < 150:
            errors.append(f"reason أقصر من 150 حرفاً: {head}")

    # 8) توزيع الصعوبة: 15 سهل / 33 متوسط / 12 صعب
    dc = Counter(q.get("diff") for q in QUESTIONS)
    if dc.get("سهل", 0) != 15 or dc.get("متوسط", 0) != 33 or dc.get("صعب", 0) != 12:
        errors.append(f"توزيع الصعوبة غير مطابق: {dict(dc)}")

    # 9) توازن صح/خطأ في أسئلة tf: نصف/نصف
    tc = Counter(q.get("correct") for q in QUESTIONS if q.get("qtype") == "tf")
    if tc.get("صح", 0) != 15 or tc.get("خطأ", 0) != 15:
        errors.append(f"توازن tf غير نصف/نصف: {dict(tc)}")

    # 10) لا حروف لاتينية داخل نصوص المحتوى
    for c in NEW_CONCEPTS:
        for k in ("chapter", "name", "explanation", "example"):
            if _LATIN.search(c.get(k, "")):
                errors.append(f"حروف لاتينية في {c['cid']}.{k}")
    for q in QUESTIONS:
        for k in ("question", "a", "b", "c", "d", "correct", "reason"):
            v = q.get(k)
            if v and _LATIN.search(str(v)):
                errors.append(f"حروف لاتينية في سؤال {q.get('cid')} ({k})")

    return errors


