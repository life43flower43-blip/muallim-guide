import json

BANK = 'public/data/qbank.json'
d = json.load(open(BANK, encoding='utf-8'))
Q = {q['id']: q for q in d['questions']}
log = []

def set_options(qid, texts, correct_idx, reason=None):
    q = Q[qid]
    assert len(q['options']) == len(texts), f'{qid}: عدد الخيارات'
    for i, t in enumerate(texts, 1):
        q['options'][i - 1]['text'] = t
        q['options'][i - 1]['isCorrect'] = (i == correct_idx)
    q['correct'] = texts[correct_idx - 1]
    if reason:
        q['reason'] = reason
    log.append(f'{qid}: مشتتات جديدة، الصواب خ{correct_idx}' + (' + تفسير محدث' if reason else ''))

