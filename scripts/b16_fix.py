from pathlib import Path

def strip_entry(path, full_line):
    p = Path(path)
    t = p.read_text(encoding='utf-8')
    t2 = t.replace(full_line + '\n', '')
    assert t2 != t, f'لم يُعثر على: {full_line[:60]}'
    p.write_text(t2, encoding='utf-8')

def swap(path, old, new):
    p = Path(path)
    t = p.read_text(encoding='utf-8')
    assert old in t, f'لم يُعثر على: {old[:60]}'
    p.write_text(t.replace(old, new), encoding='utf-8')

