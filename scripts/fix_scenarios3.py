applied, skipped = 0, []
for ln, old, new in FIXES:
    if old in lines[ln - 1]:
        lines[ln - 1] = lines[ln - 1].replace(old, new)
        applied += 1
    else:
        skipped.append((ln, old[:40]))

with open(FP, "w", encoding="utf-8") as f:
    f.writelines(lines)

print(f"\nتم تطبيق {applied} إصلاحاً؛ متخطى: {len(skipped)}")
for ln, old in skipped:
    print(f"  SKIP سطر {ln}: «{old}» غير موجود حرفياً")
