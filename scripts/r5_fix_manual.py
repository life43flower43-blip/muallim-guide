import json

BANK = 'public/data/qbank.json'
d = json.load(open(BANK, encoding='utf-8'))
Q = {q['id']: q for q in d['questions']}
log = []

def replace(qid, old, new, field='reason'):
    q = Q[qid]
    txt = q[field]
    if old not in txt:
        raise AssertionError(f'{qid}: النص القديم غير موجود: {old[:60]}')
    q[field] = txt.replace(old, new, 1)
    log.append(f'{qid}: «{old[:70]}» → «{new[:70]}»')

def swap_ordinal(qid, old_clause, new_clause):
    replace(qid, old_clause, new_clause)

def set_correct(qid, new_correct_text):
    """تغيير مفتاح الإجابة: correct + أعلام isCorrect"""
    q = Q[qid]
    found = False
    for o in q['options']:
        o['isCorrect'] = (o['text'] == new_correct_text)
        if o['isCorrect']:
            found = True
    if not found:
        raise AssertionError(f'{qid}: الخيار الجديد غير موجود')
    q['correct'] = new_correct_text
    log.append(f'{qid}: مفتاح الإجابة → «{new_correct_text[:60]}»')

